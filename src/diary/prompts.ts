/**
 * 日记提取相关的 LLM Prompt 模板
 */

/**
 * 回忆识别 Prompt
 * 判断用户消息是否包含回忆性内容（过去的事，跨天以上）
 */
export const RECALL_DETECTION_PROMPT = `你是一个回忆识别助手。你的任务是判断用户的消息是否包含"回忆性内容"。

回忆性内容的定义：
- 用户讲述的是**过去的事情**（事件时间至少在一天以前）
- 跨天以上的回忆才算，当天发生的事情不算回忆
- 模糊时间表达如"去年夏天"、"大三那年"、"那次旅行"也算回忆

非回忆性内容：
- 当天的日常事务（如"今天吃了什么"、"刚才在开会"）
- 未来计划（如"明天打算去..."）
- 纯技术讨论、问题咨询
- 虚构内容、假设场景

请分析以下用户消息，判断是否包含回忆性内容。

返回格式（严格 JSON）：
\`\`\`json
{
  "isRecall": boolean,
  "reason": string,
  "confidence": number
}
\`\`\`

字段说明：
- isRecall: true 表示包含回忆性内容
- reason: 判断理由（简短说明）
- confidence: 置信度 (0-1)，>0.7 时高置信

用户消息：
{messages}`;

/**
 * 结构化提取 Prompt
 * 从回忆性内容中提炼出结构化的日记条目
 */
export const EXTRACTION_PROMPT = `你是一个日记提炼助手。你的任务是从用户的回忆性内容中提炼出结构化的日记条目。

请提取以下字段：

1. **eventDate** (事件日期)
   - 用户回忆的那个时间
   - 格式：YYYY-MM-DD（如 2024-03-15）
   - 如果时间完全未知，返回 null
   - 如果是模糊时间（如"去年夏天"），推断一个大概日期

2. **content** (内容)
   - 提炼后的日记正文
   - 保持用户原意，但去除冗余、口语化表达
   - 形成连贯、可读的叙述

3. **people** (人物)
   - 提及的人物姓名
   - 返回数组，如 ["张三", "李四"]
   - 如果没有人物，返回空数组 []

4. **locations** (地点)
   - 提及的地点名称
   - 返回数组，如 ["北京", "故宫"]
   - 如果没有地点，返回空数组 []

5. **emotions** (情感)
   - 情感标签
   - 返回数组，如 ["开心", "怀念", "感动"]
   - 如果没有明显情感，返回空数组 []

6. **tags** (标签)
   - 其他自定义标签
   - 返回数组，如 ["旅行", "美食", "毕业"]
   - 如果没有标签，返回空数组 []

返回格式（严格 JSON）：
\`\`\`json
{
  "eventDate": string | null,
  "content": string,
  "people": string[],
  "locations": string[],
  "emotions": string[],
  "tags": string[]
}
\`\`\`

重要：
- eventDate 和 content 是必需字段
- eventDate 可以是 null（当时间完全未知时）
- 其他字段如果无法提取，返回空数组 []
- 必须返回有效的 JSON，不要添加任何额外文本

用户消息：
{messages}`;
